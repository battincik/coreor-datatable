import path from 'node:path'
import assert from 'node:assert/strict'
import React from 'react'
import { JSDOM } from 'jsdom'
import { createServer } from 'vite'

const dom = new JSDOM('<!DOCTYPE html><html><body></body></html>', { url: 'http://localhost/' })
for (const name of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'MutationObserver', 'Event', 'CustomEvent']) Object.defineProperty(globalThis, name, { configurable: true, value: dom.window[name] })
globalThis.getComputedStyle = dom.window.getComputedStyle
globalThis.requestAnimationFrame = callback => setTimeout(callback, 0)
globalThis.cancelAnimationFrame = clearTimeout
globalThis.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} }
dom.window.HTMLElement.prototype.scrollTo = function ({ top = 0 }) { this.scrollTop = top }
const { render, fireEvent, cleanup, waitFor } = await import('@testing-library/react')
const vite = await createServer({ resolve: { alias: { '@': path.resolve('src') } }, server: { middlewareMode: true }, appType: 'custom' })
try {
  const { GridCellEditor } = await vite.ssrLoadModule('/src/components/grid-column-controls.tsx')
  const { matchesColumnFilter } = await vite.ssrLoadModule('/src/components/grid-filter-utils.ts')
  const { EnterpriseGrid } = await vite.ssrLoadModule('/src/components/enterprise-grid.tsx')
  assert.equal(matchesColumnFilter('price', 49, { op: 'between', min: 40, max: 50 }), true)
  assert.equal(matchesColumnFilter('progress', 60, { op: 'between', min: 0, max: 50 }), false)
  assert.equal(matchesColumnFilter('tags', ['API', 'VIP'], { values: ['API', 'Trial'], mode: 'all' }), false)
  assert.equal(matchesColumnFilter('tags', ['API', 'VIP'], { values: ['API', 'Trial'], mode: 'any' }), true)
  assert.equal(matchesColumnFilter('status', 'active', { values: ['active'] }), true)
  assert.equal(matchesColumnFilter('timestamp', '2026-09-25T23:30:00Z', { from: '2026-09-25', to: '2026-09-25' }), true)
  assert.equal(matchesColumnFilter('date', '2026-09-26', { to: '2026-09-25' }), false)
  assert.equal(matchesColumnFilter('boolean', false, false), true)
  assert.equal(matchesColumnFilter('boolean', true, false), false)
  assert.equal(matchesColumnFilter('duration', 3600, { op: 'between', min: 3500, max: 3700 }), true)
  assert.equal(matchesColumnFilter('fileSize', 1_500_000, { op: '>', value: 1_000_000 }), true)
  assert.equal(matchesColumnFilter('rating', 4.5, { op: 'between', min: 4, max: 5 }), true)
  assert.equal(matchesColumnFilter('color', '#836FFF', { values: ['#836FFF'] }), true)
  assert.equal(matchesColumnFilter('trend', { points: [100, 130] }, { op: '>', value: 20 }), true)

  let saved
  let view = render(React.createElement(GridCellEditor, { column: { key: 'tags', title: 'Tags', kind: 'tags' }, row: { id: 1 }, value: ['API'], onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('Tags düzenle'), { target: { value: 'API, VIP' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.deepEqual(saved, ['API', 'VIP'])
  cleanup()
  view = render(React.createElement(GridCellEditor, { column: { key: 'enabled', title: 'Enabled', kind: 'boolean' }, row: { id: 1 }, value: false, onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('Enabled düzenle'), { target: { value: 'true' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.equal(saved, true)
  cleanup()
  view = render(React.createElement(GridCellEditor, { column: { key: 'fileSize', title: 'Size', kind: 'fileSize' }, row: { id: 1 }, value: 1000, onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('Size birim'), { target: { value: 'MB' } })
  fireEvent.change(view.getByLabelText('Size düzenle'), { target: { value: '1.5' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.equal(saved, 1_500_000)
  cleanup()
  view = render(React.createElement(GridCellEditor, { column: { key: 'trend', title: 'Trend', kind: 'trend' }, row: { id: 1 }, value: { points: [1, 2] }, onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('Trend düzenle'), { target: { value: '10, 15, 20' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.deepEqual(saved, { points: [10, 15, 20] })
  cleanup()
  view = render(React.createElement(GridCellEditor, { column: { key: 'url', title: 'URL', kind: 'url' }, row: { id: 1 }, value: 'https://example.com', onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('URL düzenle'), { target: { value: 'javascript:alert(1)' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.ok(view.getByRole('alert').textContent.includes('http(s)'))
  cleanup()
  view = render(React.createElement(GridCellEditor, { column: { key: 'rating', title: 'Rating', kind: 'rating', cellOptions: { ratingMax: 5, ratingStep: 0.5 } }, row: { id: 1 }, value: 4, onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('Rating düzenle'), { target: { value: '4.3' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.ok(view.getByRole('alert').textContent.includes('0.5 steps'))
  cleanup()
  view = render(React.createElement(GridCellEditor, { column: { key: 'email', title: 'Email', kind: 'email' }, row: { id: 1 }, value: 'a@example.com', onSave: value => { saved = value }, onCancel() {} }))
  fireEvent.change(view.getByLabelText('Email düzenle'), { target: { value: 'invalid' } })
  fireEvent.click(view.getByLabelText('Değişikliği kaydet'))
  assert.equal(view.getByRole('alert').textContent, 'Invalid email address')
  assert.deepEqual(saved, { points: [10, 15, 20] })
  cleanup()

  const requests = []
  const props = { columns: [{ key: 'name', title: 'Name' }], title: 'Server selection', serverMode: true, totalRows: 3, pagination: { initialPageSize: 1 }, onExportRequest: request => { requests.push(request) } }
  view = render(React.createElement(EnterpriseGrid, { ...props, data: [{ id: 1, name: 'First' }] }))
  fireEvent.click(view.getByLabelText('Bu sayfadaki satırları seç'))
  assert.ok(view.container.textContent.includes('1 selected across pages'))
  fireEvent.click(view.getByLabelText('Sonraki sayfa'))
  view.rerender(React.createElement(EnterpriseGrid, { ...props, data: [{ id: 2, name: 'Second' }] }))
  fireEvent.click(view.getByLabelText('Bu sayfadaki satırları seç'))
  assert.ok(view.container.textContent.includes('2 selected across pages'))
  fireEvent.click(view.getByText('Export selected'))
  await waitFor(() => assert.equal(requests.length, 1))
  assert.deepEqual(requests[0].selectedIds.sort(), ['1', '2'])
  assert.equal(requests[0].scope, 'selected')
  assert.deepEqual(requests[0].columnKeys, ['name'])
  assert.equal(requests[0].query.pageIndex, 1)
  fireEvent.click(view.getByLabelText('Seçimi temizle'))
  fireEvent.pointerDown(view.getByText('Export'), { button: 0, ctrlKey: false, pointerType: 'mouse' })
  await waitFor(() => assert.ok(dom.window.document.querySelector('[role="menu"]')))
  fireEvent.click(view.getByText('All filtered results CSV'))
  await waitFor(() => assert.equal(requests.length, 2))
  assert.equal(requests[1].scope, 'filtered')
  assert.deepEqual(requests[1].selectedIds, [])
  cleanup()
  console.log('Grid features: typed filters, editors, validation, cross-page selection and server export passed')
} finally { await vite.close(); dom.window.close() }
